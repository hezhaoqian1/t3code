"""Generates the two halves of the 方德 mark used by the loading screen.

The desktop icon (resources/icon.png) is the mark on a white background. This
turns white into transparency (keeping the soft fades), splits the purple and
navy pieces into separate images so the loading screen can animate them, and
writes:

  apps/web/public/boot-mark-purple.png, boot-mark-navy.png  (web boot shell, React)
  apps/desktop/src/window/bootMarkImages.ts                 (inlined into the
                                                             Electron startup document)

Run from the repo root after the icon changes:  python apps/desktop/scripts/generate-boot-mark.py
"""

import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
ICON = ROOT / "apps/desktop/resources/icon.png"
WEB_PUBLIC = ROOT / "apps/web/public"
DESKTOP_MODULE = ROOT / "apps/desktop/src/window/bootMarkImages.ts"
# The mark's bounds inside the 1024px icon, with a small margin.
CROP = (96, 112, 936, 940)
WIDTH = 192


def split_halves() -> tuple[Image.Image, Image.Image]:
    source = Image.open(ICON).convert("RGBA").crop(CROP)
    width, height = source.size
    purple = Image.new("RGBA", source.size, (0, 0, 0, 0))
    navy = Image.new("RGBA", source.size, (0, 0, 0, 0))
    src, dst_purple, dst_navy = source.load(), purple.load(), navy.load()
    for y in range(height):
        for x in range(width):
            r, g, b, _ = src[x, y]
            # White-to-alpha: the strongest channel's distance from white is the coverage.
            alpha = max(255 - r, 255 - g, 255 - b) / 255
            if alpha < 0.02:
                continue
            red, green, blue = (
                max(0, min(255, round((c - 255 * (1 - alpha)) / alpha))) for c in (r, g, b)
            )
            pixel = (red, green, blue, round(alpha * 255))
            (dst_purple if red > blue else dst_navy)[x, y] = pixel
    size = (WIDTH, round(WIDTH * height / width))
    return purple.resize(size, Image.LANCZOS), navy.resize(size, Image.LANCZOS)


def png_bytes(image: Image.Image) -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def main() -> None:
    purple, navy = split_halves()
    encoded = {}
    for name, image in (("purple", purple), ("navy", navy)):
        data = png_bytes(image)
        (WEB_PUBLIC / f"boot-mark-{name}.png").write_bytes(data)
        encoded[name] = base64.b64encode(data).decode("ascii")
    DESKTOP_MODULE.write_text(
        "// Generated by apps/desktop/scripts/generate-boot-mark.py; do not edit.\n"
        "// The two halves of the 方德 mark, inlined into the Electron startup document\n"
        "// (it renders before the local service can serve the web copies).\n"
        f'export const BOOT_MARK_PURPLE_DATA_URL =\n  "data:image/png;base64,{encoded["purple"]}";\n'
        f'export const BOOT_MARK_NAVY_DATA_URL =\n  "data:image/png;base64,{encoded["navy"]}";\n',
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {WEB_PUBLIC}/boot-mark-*.png and {DESKTOP_MODULE}")


if __name__ == "__main__":
    main()
